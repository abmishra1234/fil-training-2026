"""Task 2 -- immutable, hashable ledger records.

A ``Transaction`` is a fact that happened. Once created it never changes, which
is why it is frozen and hashable: you can put transactions in a ``set`` to
de-duplicate a replayed batch.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Optional

from minibank.money import Money


class TransactionType(enum.Enum):
    """The kinds of ledger entry this system can produce.

    Already complete -- use these members, do not invent new strings.
    """

    DEPOSIT = "DEPOSIT"
    WITHDRAWAL = "WITHDRAWAL"
    TRANSFER_IN = "TRANSFER_IN"
    TRANSFER_OUT = "TRANSFER_OUT"
    INTEREST = "INTEREST"
    FEE = "FEE"

    @property
    def is_credit(self) -> bool:
        """True for entries that increase the balance."""
        return self in {
            TransactionType.DEPOSIT,
            TransactionType.TRANSFER_IN,
            TransactionType.INTEREST,
        }

    def __str__(self) -> str:  # pragma: no cover - cosmetic
        return self.value


def _utc_now() -> datetime:
    """Timezone-aware 'now'. Naive datetimes are a bug in financial records."""
    return datetime.now(timezone.utc)


